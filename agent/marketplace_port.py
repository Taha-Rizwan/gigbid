"""The single marketplace interface (R1). Two adapters implement it:
mcp_servers/marketplace/adapters/gigsim.py and .../upwork_live.py. The marketplace MCP server
picks one from config, so agents (which only see MCP tools) cannot tell which is in use."""

from __future__ import annotations

from typing import Any, Protocol, runtime_checkable


class MarketplaceError(Exception):
    def __init__(self, code: str, detail: str = "", status: int = 400, retry_after: float | None = None,
                 data: dict | None = None):
        super().__init__(f"{code}: {detail}")
        self.code, self.detail, self.status, self.retry_after, self.data = code, detail, status, retry_after, data or {}


class MarketplaceUnavailable(MarketplaceError):
    def __init__(self, detail: str = "marketplace unavailable"):
        super().__init__("marketplace_unavailable", detail, 503)


@runtime_checkable
class MarketplacePort(Protocol):
    name: str

    # ---- read ----
    async def search_jobs(self, query: str = "", category: str | None = None, limit: int = 20,
                          offset: int = 0, posted_after: str | None = None) -> dict[str, Any]: ...
    async def get_job(self, job_id: str) -> dict[str, Any]: ...
    async def get_client_history(self, client_id: str) -> dict[str, Any]: ...
    async def get_connects_balance(self) -> dict[str, Any]: ...
    async def get_market_stats(self, category: str | None = None) -> dict[str, Any]: ...
    async def get_policy(self) -> dict[str, Any]: ...
    async def list_proposals(self, status: str | None = None) -> list[dict[str, Any]]: ...
    async def list_threads(self) -> list[dict[str, Any]]: ...
    async def list_messages(self, thread_id: str) -> list[dict[str, Any]]: ...
    async def get_events(self, after: int = 0, limit: int = 100) -> dict[str, Any]: ...
    async def health(self) -> dict[str, Any]: ...

    # ---- write (always behind human approval in the graph) ----
    async def create_proposal_draft(self, payload: dict[str, Any], idempotency_key: str) -> dict[str, Any]: ...
    async def submit_proposal(self, draft_id: str, idempotency_key: str, dry_run: bool = False) -> dict[str, Any]: ...
    async def send_message(self, thread_id: str, text: str, idempotency_key: str,
                           dry_run: bool = False) -> dict[str, Any]: ...
