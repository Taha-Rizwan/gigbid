"""Deploy GigBid to a Hugging Face Docker Space (public URL with a reviewer login).

    python scripts/deploy_hf.py            # create/update the Space, upload code, set secrets

Uploads only git-tracked files (so nothing ignored, like .env or raw data, can leak), places
infra/hf/Dockerfile at the Space root, and sets runtime secrets from .env. Secrets generated here
(app secret, encryption key, MCP token, reviewer password) are appended to the local .env so the
owner has them; they are never printed.
"""

from __future__ import annotations

import os
import secrets
import shutil
import subprocess
import tempfile
from pathlib import Path

from cryptography.fernet import Fernet
from dotenv import dotenv_values
from huggingface_hub import HfApi

ROOT = Path(__file__).resolve().parents[1]
SPACE_README = """---
title: GigBid
emoji: 🤝
colorFrom: indigo
colorTo: blue
sdk: docker
app_port: 7860
pinned: false
short_description: Multi-agent freelancer copilot (AI-4016)
---

GigBid: LangGraph agents find freelance jobs, check risk and fit, and draft proposals grounded in
portfolio evidence. A human approves every proposal and message. Source: {repo}
"""


def ensure_generated_secrets(env: dict) -> dict:
    gen = {
        "APP_SECRET_KEY": lambda: secrets.token_urlsafe(48),
        "TOKEN_ENCRYPTION_KEY": lambda: Fernet.generate_key().decode(),
        "MCP_AUTH_TOKEN": lambda: secrets.token_urlsafe(32),
        "REVIEWER_PASSWORD": lambda: secrets.token_urlsafe(12),
    }
    new = {k: f() for k, f in gen.items() if not env.get(k)}
    if new:
        with open(ROOT / ".env", "a", encoding="utf-8") as f:
            f.write("\n# generated by scripts/deploy_hf.py\n" + "".join(f"{k}={v}\n" for k, v in new.items()))
    return env | new


def main() -> None:
    env = ensure_generated_secrets(dotenv_values(ROOT / ".env"))
    user = env["HF_USERNAME"]
    repo_id = f"{user}/gigbid"
    url = f"https://{user.lower()}-gigbid.hf.space"
    api = HfApi(token=env["HF_TOKEN"])
    api.create_repo(repo_id, repo_type="space", space_sdk="docker", private=False, exist_ok=True)

    runtime = {
        "DATABASE_URL": env.get("DATABASE_URL"), "REDIS_URL": env.get("REDIS_URL"),
        "GROQ_API_KEY": env.get("GROQ_API_KEY"), "ANTHROPIC_API_KEY": env.get("ANTHROPIC_API_KEY"),
        "CEREBRAS_API_KEY": env.get("CEREBRAS_API_KEY"), "LANGSMITH_API_KEY": env.get("LANGSMITH_API_KEY"),
        "APP_SECRET_KEY": env["APP_SECRET_KEY"], "TOKEN_ENCRYPTION_KEY": env["TOKEN_ENCRYPTION_KEY"],
        "MCP_AUTH_TOKEN": env["MCP_AUTH_TOKEN"], "REVIEWER_PASSWORD": env["REVIEWER_PASSWORD"],
    }
    for k, v in runtime.items():
        if v:
            api.add_space_secret(repo_id, k, v)
    for k, v in {"PUBLIC_BASE_URL": url, "CORS_ORIGINS": f'["{url}"]', "LANGSMITH_TRACING": "true",
                 "LANGSMITH_PROJECT": "gigbid", "MODEL_PROFILE": os.environ.get("DEPLOY_MODEL_PROFILE", "open"),
                 "WORKER_MODE": "arq", "GIGSIM_LLM_DISABLED": "1"}.items():
        api.add_space_variable(repo_id, k, v)

    files = subprocess.run(["git", "ls-files"], cwd=ROOT, capture_output=True, text=True, check=True).stdout.split()
    with tempfile.TemporaryDirectory() as tmp:
        stage = Path(tmp)
        for f in files:
            if f.startswith(("apps/web/node_modules", ".github/")):
                continue
            dst = stage / f
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(ROOT / f, dst)
        shutil.copy2(ROOT / "infra" / "hf" / "Dockerfile", stage / "Dockerfile")
        (stage / "README.md").write_text(SPACE_README.format(repo=env.get("GITHUB_REPO_URL", "")), encoding="utf-8")
        api.upload_folder(repo_id=repo_id, repo_type="space", folder_path=str(stage),
                          commit_message="Deploy GigBid", delete_patterns=["*"])
    print(f"Space: https://huggingface.co/spaces/{repo_id}\nApp:   {url}\nReviewer login: {env.get('REVIEWER_EMAIL', 'reviewer@gigbid.dev')} "
          "(password: REVIEWER_PASSWORD in your local .env)")


if __name__ == "__main__":
    main()
